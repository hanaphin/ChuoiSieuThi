-- ============================================================================
-- ĐỀ TÀI 1: HỆ THỐNG QUẢN LÝ CHUỖI SIÊU THỊ ĐA CHI NHÁNH
-- FILE 05: TRUY VẤN BÁO CÁO TỔNG HỢP XUYÊN PDB (CROSS-PDB REPORTING)
-- Thực thi từ CDB$ROOT bằng Common User c##admin_chuoi
-- Sử dụng mệnh đề CONTAINERS() của Oracle Database 23ai Multitenant
-- ============================================================================

-- Chuyển phiên làm việc về CDB$ROOT
ALTER SESSION SET CONTAINER = CDB$ROOT;

-- BÁO CÁO 1: TỔNG HỢP DOANH THU TOÀN CHUỖI THEO TỪNG PDB (CHI NHÁNH)
-- Sử dụng CONTAINERS(HOADON) và hàm CON_ID_TO_CON_NAME()
SELECT 
    c.CON_ID,
    CON_ID_TO_CON_NAME(c.CON_ID) AS TEN_PDB,
    c.MA_CN,
    COUNT(c.MA_HD) AS TONG_SO_DON,
    SUM(c.TONG_TIEN) AS TONG_DOANH_THU,
    AVG(c.TONG_TIEN) AS GIA_TRI_DON_TRUNG_BINH
FROM CONTAINERS(HOADON) c
WHERE c.TRANG_THAI = 'DA_THANH_TOAN'
GROUP BY c.CON_ID, c.MA_CN
ORDER BY TONG_DOANH_THU DESC;

-- BÁO CÁO 2: TỔNG HỢP TỒN KHO TOÀN HỆ THỐNG XUYÊN SUỐT CÁC PDB
SELECT 
    CON_ID_TO_CON_NAME(t.CON_ID) AS TEN_PDB,
    t.MA_CN,
    sp.TEN_SP,
    dm.TEN_DM,
    t.SO_LUONG_TON,
    t.NGUONG_CANH_BAO,
    CASE 
        WHEN t.SO_LUONG_TON <= t.NGUONG_CANH_BAO THEN 'CANH_BAO_SAP_HET'
        ELSE 'AN_TOAN'
    END AS TINH_TRANG_KHO
FROM CONTAINERS(TONKHO) t
JOIN CONTAINERS(SANPHAM) sp ON t.MA_SP = sp.MA_SP AND t.CON_ID = sp.CON_ID
JOIN CONTAINERS(DANHMUC) dm ON sp.MA_DM = dm.MA_DM AND sp.CON_ID = dm.CON_ID
ORDER BY t.SO_LUONG_TON ASC;

-- BÁO CÁO 3: TOP 5 SẢN PHẨM BÁN CHẠY NHẤT TOÀN CHUỖI SIÊU THỊ
SELECT 
    sp.MA_SP,
    sp.TEN_SP,
    SUM(ct.SO_LUONG) AS TONG_SO_LUONG_DA_BAN,
    SUM(ct.THANH_TIEN) AS TONG_TIEN_THU_VE
FROM CONTAINERS(CTHOADON) ct
JOIN CONTAINERS(SANPHAM) sp ON ct.MA_SP = sp.MA_SP AND ct.CON_ID = sp.CON_ID
GROUP BY sp.MA_SP, sp.TEN_SP
ORDER BY TONG_SO_LUONG_DA_BAN DESC
FETCH FIRST 5 ROWS ONLY;

-- BÁO CÁO 4: SO SÁNH CHÊNH LỆCH TỒN KHO GIỮA CÁC CHI NHÁNH ĐỂ ĐỀ XUẤT ĐIỀU CHUYỂN
-- Pivot/Group theo mặt hàng trên tất cả các chi nhánh
SELECT 
    sp.MA_SP,
    sp.TEN_SP,
    NVL(SUM(CASE WHEN CON_ID_TO_CON_NAME(t.CON_ID) = 'PDB_QUAN1' THEN t.SO_LUONG_TON END), 0) AS TON_QUAN_1,
    NVL(SUM(CASE WHEN CON_ID_TO_CON_NAME(t.CON_ID) = 'PDB_QUAN7' THEN t.SO_LUONG_TON END), 0) AS TON_QUAN_7,
    NVL(SUM(CASE WHEN CON_ID_TO_CON_NAME(t.CON_ID) = 'PDB_THUDUC' THEN t.SO_LUONG_TON END), 0) AS TON_THU_DUC,
    SUM(t.SO_LUONG_TON) AS TONG_TON_TOAN_CHUOI
FROM CONTAINERS(TONKHO) t
JOIN CONTAINERS(SANPHAM) sp ON t.MA_SP = sp.MA_SP AND t.CON_ID = sp.CON_ID
GROUP BY sp.MA_SP, sp.TEN_SP
ORDER BY TONG_TON_TOAN_CHUOI DESC;
