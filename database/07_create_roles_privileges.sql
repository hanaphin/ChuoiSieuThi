-- ============================================================================
-- BƯỚC 1: TẠO VÀ CẤP QUYỀN CHO COMMON ROLES TẠI CDB$ROOT
-- ============================================================================
ALTER SESSION SET CONTAINER = CDB$ROOT;

-- 1. Xóa các Common Role cũ nếu tồn tại
BEGIN
    EXECUTE IMMEDIATE 'DROP ROLE c##role_quan_tri_chuoi';
    EXECUTE IMMEDIATE 'DROP ROLE c##role_ban_giam_doc';
EXCEPTION
    WHEN OTHERS THEN NULL;
END;
/

-- 2. Tạo Common Role: Quản trị viên hạ tầng toàn chuỗi (HQ IT Admin)
CREATE ROLE c##role_quan_tri_chuoi CONTAINER = ALL;

-- Cấp quyền quản trị container, cắm/rút PDB, quản lý người dùng
GRANT CREATE SESSION TO c##role_quan_tri_chuoi CONTAINER = ALL;
GRANT CREATE PLUGGABLE DATABASE TO c##role_quan_tri_chuoi CONTAINER = ALL;
GRANT ALTER PLUGGABLE DATABASE TO c##role_quan_tri_chuoi CONTAINER = ALL;
GRANT CREATE USER, ALTER USER, DROP USER TO c##role_quan_tri_chuoi CONTAINER = ALL;
GRANT CREATE ROLE, GRANT ANY ROLE TO c##role_quan_tri_chuoi CONTAINER = ALL;

-- 3. Tạo Common Role: Ban Giám Đốc chuỗi siêu thị (HQ Executive / Auditor)
CREATE ROLE c##role_ban_giam_doc CONTAINER = ALL;

-- Cấp quyền đăng nhập và đọc báo cáo hợp nhất trên toàn bộ containers
GRANT CREATE SESSION TO c##role_ban_giam_doc CONTAINER = ALL;
GRANT SELECT ANY TABLE TO c##role_ban_giam_doc CONTAINER = ALL;
GRANT READ ANY TABLE TO c##role_ban_giam_doc CONTAINER = ALL;

-- 4. Tạo người dùng mẫu cho tầng Toàn Chuỗi (CDB$ROOT)
-- User Quản trị viên
CREATE USER c##admin_it IDENTIFIED BY ITAdmin2026# CONTAINER = ALL;
GRANT c##role_quan_tri_chuoi TO c##admin_it CONTAINER = ALL;

-- User Ban Giám Đốc
CREATE USER c##giam_doc IDENTIFIED BY Director2026# CONTAINER = ALL;
GRANT c##role_ban_giam_doc TO c##giam_doc CONTAINER = ALL;


-- ============================================================================
-- BƯỚC 2: TẠO LOCAL ROLES VÀ GÁN QUYỀN TẠI PDB CHI NHÁNH QUẬN 1 (pdb_quan1)
-- ============================================================================
ALTER SESSION SET CONTAINER = pdb_quan1;

-- Xóa Local Roles cũ nếu có
BEGIN
    EXECUTE IMMEDIATE 'DROP ROLE ROLE_QUAN_LY_CHI_NHANH';
    EXECUTE IMMEDIATE 'DROP ROLE ROLE_THU_NGAN';
    EXECUTE IMMEDIATE 'DROP ROLE ROLE_NHAN_VIEN_KHO';
EXCEPTION
    WHEN OTHERS THEN NULL;
END;
/

-- 1. Local Role: Quản lý chi nhánh (Store Manager)
CREATE ROLE ROLE_QUAN_LY_CHI_NHANH;
GRANT CREATE SESSION TO ROLE_QUAN_LY_CHI_NHANH;
GRANT SELECT, INSERT, UPDATE ON SANPHAM TO ROLE_QUAN_LY_CHI_NHANH;
GRANT SELECT, INSERT, UPDATE ON DANHMUC TO ROLE_QUAN_LY_CHI_NHANH;
GRANT SELECT, INSERT, UPDATE ON TONKHO TO ROLE_QUAN_LY_CHI_NHANH;
GRANT SELECT, INSERT, UPDATE ON HOADON TO ROLE_QUAN_LY_CHI_NHANH;
GRANT SELECT, INSERT ON CTHOADON TO ROLE_QUAN_LY_CHI_NHANH;
GRANT SELECT ON LICHSU_TONKHO TO ROLE_QUAN_LY_CHI_NHANH;
GRANT EXECUTE ON PKG_QUANLY_BANHANG TO ROLE_QUAN_LY_CHI_NHANH;

-- 2. Local Role: Thu ngân bán hàng tại quầy POS (Cashier)
CREATE ROLE ROLE_THU_NGAN;
GRANT CREATE SESSION TO ROLE_THU_NGAN;
GRANT SELECT ON SANPHAM TO ROLE_THU_NGAN;
GRANT SELECT ON DANHMUC TO ROLE_THU_NGAN;
GRANT SELECT, INSERT ON HOADON TO ROLE_THU_NGAN;
GRANT SELECT, INSERT ON CTHOADON TO ROLE_THU_NGAN;
-- Thu ngân chỉ được thực thi Package tạo đơn, KHÔNG được UPDATE bảng TONKHO trực tiếp
GRANT EXECUTE ON PKG_QUANLY_BANHANG TO ROLE_THU_NGAN;

-- 3. Local Role: Nhân viên thủ kho chi nhánh (Inventory Keeper)
CREATE ROLE ROLE_NHAN_VIEN_KHO;
GRANT CREATE SESSION TO ROLE_NHAN_VIEN_KHO;
GRANT SELECT ON SANPHAM TO ROLE_NHAN_VIEN_KHO;
GRANT SELECT ON DANHMUC TO ROLE_NHAN_VIEN_KHO;
GRANT SELECT, UPDATE ON TONKHO TO ROLE_NHAN_VIEN_KHO;
GRANT SELECT ON LICHSU_TONKHO TO ROLE_NHAN_VIEN_KHO;
GRANT EXECUTE ON PKG_QUANLY_BANHANG TO ROLE_NHAN_VIEN_KHO;

-- 4. Tạo các Local Users đại diện tại Chi nhánh Quận 1
CREATE USER q1_quanly IDENTIFIED BY Q1Manager2026#;
GRANT ROLE_QUAN_LY_CHI_NHANH TO q1_quanly;
ALTER USER q1_quanly DEFAULT ROLE ROLE_QUAN_LY_CHI_NHANH;

CREATE USER q1_thungan01 IDENTIFIED BY Q1Cashier2026#;
GRANT ROLE_THU_NGAN TO q1_thungan01;
ALTER USER q1_thungan01 DEFAULT ROLE ROLE_THU_NGAN;

CREATE USER q1_thukho01 IDENTIFIED BY Q1Keeper2026#;
GRANT ROLE_NHAN_VIEN_KHO TO q1_thukho01;
ALTER USER q1_thukho01 DEFAULT ROLE ROLE_NHAN_VIEN_KHO;


