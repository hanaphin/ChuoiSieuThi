-- 1. BẢNG CHI NHÁNH SIÊU THỊ (Lưu thông tin chi nhánh định danh cho PDB này)
CREATE TABLE CHINHANH (
    MA_CN VARCHAR2(20) PRIMARY KEY,
    TEN_CN NVARCHAR2(150) NOT NULL,
    PDB_NAME VARCHAR2(50) NOT NULL,
    DIA_CHI NVARCHAR2(255) NOT NULL,
    SO_DIEN_THOAI VARCHAR2(20),
    TRANG_THAI VARCHAR2(20) DEFAULT 'HOAT_DONG' CHECK (TRANG_THAI IN ('HOAT_DONG', 'BAO_TRI', 'TAM_DONG')),
    NGAY_KHAI_TRUONG DATE DEFAULT SYSDATE
);

-- 2. BẢNG DANH MỤC NGÀNH HÀNG
CREATE TABLE DANHMUC (
    MA_DM VARCHAR2(20) PRIMARY KEY,
    TEN_DM NVARCHAR2(100) NOT NULL,
    MO_TA NVARCHAR2(255)
);

-- 3. BẢNG SẢN PHẨM / HÀNG HOÁ
CREATE TABLE SANPHAM (
    MA_SP VARCHAR2(20) PRIMARY KEY,
    MA_DM VARCHAR2(20) NOT NULL,
    BARCODE VARCHAR2(30) UNIQUE,
    TEN_SP NVARCHAR2(200) NOT NULL,
    DON_VI_TINH NVARCHAR2(30) DEFAULT 'Cái',
    GIA_NIEM_YET NUMBER(12, 2) NOT NULL CHECK (GIA_NIEM_YET >= 0),
    CONSTRAINT FK_SANPHAM_DANHMUC FOREIGN KEY (MA_DM) REFERENCES DANHMUC(MA_DM)
);

-- 4. BẢNG TỒN KHO THEO CHI NHÁNH (Dữ liệu độc lập tại từng PDB)
CREATE TABLE TONKHO (
    MA_CN VARCHAR2(20) NOT NULL,
    MA_SP VARCHAR2(20) NOT NULL,
    SO_LUONG_TON NUMBER(10) DEFAULT 0 CHECK (SO_LUONG_TON >= 0),
    NGUONG_CANH_BAO NUMBER(10) DEFAULT 10,
    CAP_NHAT_CUOI TIMESTAMP DEFAULT SYSTIMESTAMP,
    PRIMARY KEY (MA_CN, MA_SP),
    CONSTRAINT FK_TONKHO_CHINHANH FOREIGN KEY (MA_CN) REFERENCES CHINHANH(MA_CN),
    CONSTRAINT FK_TONKHO_SANPHAM FOREIGN KEY (MA_SP) REFERENCES SANPHAM(MA_SP)
);

-- 5. BẢNG HOÁ ĐƠN BÁN HÀNG
CREATE TABLE HOADON (
    MA_HD VARCHAR2(30) PRIMARY KEY,
    MA_CN VARCHAR2(20) NOT NULL,
    NGAY_LAP TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    THU_NGAN NVARCHAR2(100) DEFAULT 'Thu ngân 01',
    TEN_KHACH_HANG NVARCHAR2(100) DEFAULT 'Khách lẻ',
    TONG_TIEN NUMBER(14, 2) DEFAULT 0 CHECK (TONG_TIEN >= 0),
    PHUONG_THUC_TT VARCHAR2(30) DEFAULT 'TIEN_MAT' CHECK (PHUONG_THUC_TT IN ('TIEN_MAT', 'CHUYEN_KHOAN', 'THE', 'VI_DIEN_TU')),
    TRANG_THAI VARCHAR2(20) DEFAULT 'DA_THANH_TOAN' CHECK (TRANG_THAI IN ('DA_THANH_TOAN', 'DA_HUY')),
    CONSTRAINT FK_HOADON_CHINHANH FOREIGN KEY (MA_CN) REFERENCES CHINHANH(MA_CN)
);

-- 6. BẢNG CHI TIẾT HOÁ ĐƠN
CREATE TABLE CTHOADON (
    MA_HD VARCHAR2(30) NOT NULL,
    MA_SP VARCHAR2(20) NOT NULL,
    SO_LUONG NUMBER(6) NOT NULL CHECK (SO_LUONG > 0),
    DON_GIA NUMBER(12, 2) NOT NULL CHECK (DON_GIA >= 0),
    THANH_TIEN NUMBER(14, 2) NOT NULL CHECK (THANH_TIEN >= 0),
    PRIMARY KEY (MA_HD, MA_SP),
    CONSTRAINT FK_CTHD_HOADON FOREIGN KEY (MA_HD) REFERENCES HOADON(MA_HD) ON DELETE CASCADE,
    CONSTRAINT FK_CTHD_SANPHAM FOREIGN KEY (MA_SP) REFERENCES SANPHAM(MA_SP)
);

-- 7. BẢNG NHẬT KÝ BIẾN ĐỘNG TỒN KHO (Audit Log)
CREATE TABLE LICHSU_TONKHO (
    MA_LOG NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    MA_CN VARCHAR2(20) NOT NULL,
    MA_SP VARCHAR2(20) NOT NULL,
    LOAI_GIAO_DICH VARCHAR2(30) CHECK (LOAI_GIAO_DICH IN ('BAN_HANG', 'NHAP_KHO', 'CHUYEN_DEN', 'CHUYEN_DI', 'DIEU_CHINH')),
    SO_LUONG_THAY_DOI NUMBER(10) NOT NULL,
    TON_TRUOC NUMBER(10) NOT NULL,
    TON_SAU NUMBER(10) NOT NULL,
    MA_CHUNG_TU VARCHAR2(50),
    THOI_GIAN TIMESTAMP DEFAULT SYSTIMESTAMP,
    GHI_CHU NVARCHAR2(255)
);

-- Tạo chỉ mục tối ưu truy vấn bán hàng và báo cáo
CREATE INDEX IDX_HOADON_NGAY ON HOADON(NGAY_LAP);
CREATE INDEX IDX_TONKHO_SP ON TONKHO(MA_SP);
CREATE INDEX IDX_CTHD_SP ON CTHOADON(MA_SP);
